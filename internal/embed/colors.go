// Package embed provides Discord embed building utilities.
package embed

// Discord embed colors as integers.
const (
	// ColorPrimary is the main brand color (Spotify-like green).
	ColorPrimary = 0x1DB954

	// ColorSuccess is used for successful operations.
	ColorSuccess = 0x57F287

	// ColorError is used for error messages.
	ColorError = 0xED4245

	// ColorWarning is used for warning messages.
	ColorWarning = 0xFEE75C

	// ColorInfo is used for informational messages.
	ColorInfo = 0x5865F2

	// ColorNowPlaying is used for now playing embeds.
	ColorNowPlaying = 0x1DB954

	// ColorQueue is used for queue display.
	ColorQueue = 0x5865F2

	// ColorStopped is used when playback is stopped.
	ColorStopped = 0x99AAB5
)
